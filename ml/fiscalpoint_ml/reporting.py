"""Evaluation report (Markdown + PNG charts) written by the training pipeline."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from .forecasting import BASELINES, MODEL_NAME  # noqa: E402

_BLUE, _GREY, _ORANGE = "#2a6fdb", "#9aa3ad", "#e8833a"


def _save(fig, path: Path) -> str:
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return path.name


def forecast_charts(predictions: pd.DataFrame, summary: dict, importance: pd.Series | None, out: Path) -> dict:
    charts = {}
    models = [MODEL_NAME, *BASELINES]
    maes = [summary["category_level"][m]["mae"] for m in models]
    fig, ax = plt.subplots(figsize=(7, 3.6))
    ax.barh(models[::-1], maes[::-1], color=[_GREY] * len(BASELINES) + [_BLUE])
    ax.set_xlabel("MAE per user-category-month (₹, lower is better)")
    ax.set_title("Rolling-origin backtest: model vs. baselines")
    for i, v in enumerate(maes[::-1]):
        ax.text(v, i, f" ₹{v:,.0f}", va="center", fontsize=9)
    ax.spines[["top", "right"]].set_visible(False)
    charts["mae_comparison"] = _save(fig, out / "forecast_mae_comparison.png")

    totals = predictions.groupby(["user_id", "period"])[["amount", MODEL_NAME]].sum()
    fig, ax = plt.subplots(figsize=(4.8, 4.5))
    ax.scatter(totals["amount"], totals[MODEL_NAME], s=12, alpha=0.6, color=_BLUE)
    hi = float(max(totals["amount"].max(), totals[MODEL_NAME].max()))
    ax.plot([0, hi], [0, hi], color=_GREY, lw=1, ls="--")
    ax.set_xlabel("Actual monthly total (₹)")
    ax.set_ylabel("Forecast monthly total (₹)")
    ax.set_title("Monthly totals: forecast vs. actual")
    ax.spines[["top", "right"]].set_visible(False)
    charts["actual_vs_forecast"] = _save(fig, out / "forecast_actual_vs_predicted.png")

    if importance is not None:
        top = importance.head(12)[::-1]
        fig, ax = plt.subplots(figsize=(6, 4))
        ax.barh(top.index, top.values, color=_BLUE)
        ax.set_xlabel("Permutation importance (increase in MAE, ₹)")
        ax.set_title("What drives the forecast")
        ax.spines[["top", "right"]].set_visible(False)
        charts["feature_importance"] = _save(fig, out / "forecast_feature_importance.png")
    return charts


def confusion_chart(metrics: dict, out: Path) -> str:
    labels = metrics["labels"]
    cm = np.asarray(metrics["confusion_matrix"], dtype=float)
    norm = cm / cm.sum(axis=1, keepdims=True).clip(min=1)
    fig, ax = plt.subplots(figsize=(7.5, 6.5))
    ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks(range(len(labels)), labels, rotation=60, ha="right", fontsize=8)
    ax.set_yticks(range(len(labels)), labels, fontsize=8)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("Actual")
    ax.set_title("Categorizer confusion matrix (row-normalised)")
    for i in range(len(labels)):
        for j in range(len(labels)):
            if norm[i, j] >= 0.05:
                ax.text(j, i, f"{norm[i, j]:.2f}", ha="center", va="center", fontsize=6,
                        color="white" if norm[i, j] > 0.5 else "black")
    return _save(fig, out / "categorizer_confusion_matrix.png")


def reliability_chart(budget_metrics: dict, out: Path) -> str | None:
    if not budget_metrics:
        return None
    fig, ax = plt.subplots(figsize=(4.8, 4.5))
    ax.plot([0, 1], [0, 1], color=_GREY, ls="--", lw=1, label="perfect calibration")
    for (name, entry), color in zip(budget_metrics.items(), [_ORANGE, _BLUE, "#2e9e6b"]):
        rel = entry["reliability"]
        ax.plot([r["mean_predicted"] for r in rel], [r["observed_rate"] for r in rel], marker="o", color=color,
                label=name.replace("_", " "))
    ax.set_xlabel("Predicted probability of overrun")
    ax.set_ylabel("Observed overrun rate")
    ax.set_title("Budget-risk calibration")
    ax.legend(fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    return _save(fig, out / "budget_risk_reliability.png")


def _fmt(value, pct=False):
    if value is None:
        return "–"
    return f"{value:.1%}" if pct else f"{value:,.0f}"


def write_markdown(metadata: dict, charts: dict, out: Path) -> Path:
    fc = metadata["metrics"]["forecasting"]
    cat = metadata["metrics"]["categorizer"]
    an = metadata["metrics"]["anomaly"]
    br = metadata["metrics"]["budget_risk"]
    data = metadata["data"]
    lines = [
        "# FiscalPoint model evaluation report",
        "",
        f"Generated by `python -m fiscalpoint_ml.train` on {metadata['trained_at']} "
        f"(package {metadata['package_version']}, scikit-learn {metadata['sklearn_version']}).",
        "",
        f"**Training data:** {data['source']} — {data['n_transactions']:,} transactions, {data['n_users']} users, "
        f"{data['first_date']} to {data['last_date']}.",
        "",
        "## 1. Monthly spend forecasting",
        "",
        f"Rolling-origin backtest over the last {fc['n_origins']} complete months: for each month the model is "
        "trained only on earlier months and forecasts that month. All models are scored on the same cells.",
        "",
        "| Model | MAE / category (₹) | WAPE | MAE / monthly total (₹) | WAPE (total) |",
        "|---|---:|---:|---:|---:|",
    ]
    for model in [MODEL_NAME, *BASELINES]:
        c, u = fc["category_level"][model], fc["user_total_level"][model]
        name = f"**{model}**" if model == fc["champion"] else model
        lines.append(f"| {name} | {_fmt(c['mae'])} | {_fmt(c['wape'], True)} | {_fmt(u['mae'])} | {_fmt(u['wape'], True)} |")
    lines += [
        "",
        f"* Champion: **{fc['champion']}**; MAE improvement over the best baseline ({fc['best_baseline']}): "
        f"**{fc['mae_improvement_vs_best_baseline']:.1%}**.",
        f"* 80 % prediction-interval coverage: **{fc['interval_coverage_80']:.1%}** (target 80 %).",
        "",
        f"![MAE comparison]({charts.get('mae_comparison', '')})",
        f"![Actual vs forecast]({charts.get('actual_vs_forecast', '')})",
    ]
    if "feature_importance" in charts:
        lines.append(f"![Feature importance]({charts['feature_importance']})")
    lines += [
        "",
        "## 2. Expense categorizer",
        "",
        f"Stratified hold-out ({cat['n_test']:,} test descriptions).",
        "",
        f"* Accuracy **{cat['accuracy']:.1%}**, macro-F1 **{cat['macro_f1']:.3f}**, top-3 accuracy **{cat['top3_accuracy']:.1%}**.",
        "",
        "| Category | Precision | Recall | F1 | Support |",
        "|---|---:|---:|---:|---:|",
    ]
    for label in cat["labels"]:
        row = cat["per_class"][label]
        lines.append(f"| {label} | {row['precision']:.2f} | {row['recall']:.2f} | {row['f1-score']:.2f} | {int(row['support'])} |")
    lines += ["", f"![Confusion matrix]({charts.get('confusion', '')})", "", "## 3. Anomaly detection", ""]
    if an.get("evaluated"):
        lines += [
            "Evaluated against the anomalies injected by the synthetic generator (unsupervised model, scored in-sample).",
            "",
            "| Method | Precision | Recall | F1 | Flag rate |",
            "|---|---:|---:|---:|---:|",
            f"| **Isolation Forest + ratio rule** | {an['precision']:.2f} | {an['recall']:.2f} | {an['f1']:.2f} | {an['flag_rate']:.2%} |",
        ]
        for name, b in an["baselines"].items():
            lines.append(f"| {name} | {b['precision']:.2f} | {b['recall']:.2f} | {b['f1']:.2f} | {b['flag_rate']:.2%} |")
        lines += ["", f"Score ROC-AUC {an['roc_auc']:.3f}, average precision {an['average_precision']:.3f}."]
    else:
        lines.append("No labelled anomalies in this data source, so only the synthetic-data evaluation applies.")
    lines += [
        "",
        "## 4. Budget-overrun risk",
        "",
        f"Learned within-month spending curve and forecast error scale (relative σ = {metadata['budget_risk_sigma']:.3f}).",
        "Budgets simulated as previous-3-month average × U(0.85, 1.15).",
        "",
        "| Checkpoint | User-months | Brier score | No-skill Brier | ROC-AUC |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, entry in br.items():
        lines.append(f"| {name.replace('_', ' ')} | {entry['n_user_months']} | {entry['brier_score']:.3f} | "
                     f"{entry['brier_score_no_skill']:.3f} | {entry.get('roc_auc', float('nan')):.3f} |")
    if charts.get("reliability"):
        lines += ["", f"![Reliability]({charts['reliability']})"]
    lines += ["", "See `docs/MODEL_CARD.md` for intended use, limitations and caveats.", ""]
    path = out / "REPORT.md"
    path.write_text("\n".join(lines))
    return path
