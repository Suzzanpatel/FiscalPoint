"""Write ``database/seed_demo.sql``: demo users with realistic synthetic history.

    python -m fiscalpoint_ml.data.seed_sql                  # 8 users, 24 months, ending today
    python -m fiscalpoint_ml.data.seed_sql --users 15 --months 30

Demo logins (change or delete them on any shared deployment):
    admin@fiscalpoint.test   / Admin@1234   (administrator)
    demo.user1@fiscalpoint.test ... / Demo@1234
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

from ..config import PROJECT_ROOT
from . import synthetic

# bcrypt hashes produced by PHP password_hash(); verified with password_verify().
DEMO_PASSWORD_HASH = "$2y$10$HOPwnWY8/a8EGo7GJ5Z0y.W600VpvfjYMFVK2AjEaCbyps12BuDUG"    # Demo@1234
ADMIN_PASSWORD_HASH = "$2y$10$Mtijg1cT0jgGMx7Eg2CJuunBxGMjRw884rKC8JYOfv8OQ5kYP8wXu"   # Admin@1234


def _q(value: str) -> str:
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def _insert(table: str, columns: list[str], rows: list[tuple], batch: int = 500) -> list[str]:
    out = []
    for i in range(0, len(rows), batch):
        values = ",\n".join("(" + ", ".join(row) + ")" for row in rows[i:i + batch])
        out.append(f"INSERT INTO `{table}` ({', '.join(f'`{c}`' for c in columns)}) VALUES\n{values};")
    return out


def build_sql(n_users: int = 8, n_months: int = 24, seed: int = 2026, end: date | None = None) -> str:
    data = synthetic.generate(n_users=n_users, n_months=n_months, seed=seed, end=end)
    end = end or date.today()
    lines = [
        "-- FiscalPoint demo data (synthetic; contains no real personal information).",
        f"-- Generated by: python -m fiscalpoint_ml.data.seed_sql --users {n_users} --months {n_months} --seed {seed}",
        f"-- History ends on {end.isoformat()}. Load after database/schema.sql.",
        "-- Logins: admin@fiscalpoint.test / Admin@1234, demo.user1@fiscalpoint.test / Demo@1234",
        "",
        "SET NAMES utf8mb4;",
        "START TRANSACTION;",
        "",
    ]
    users = [(str(1), _q("FiscalPoint Admin"), _q("admin@fiscalpoint.test"), _q(ADMIN_PASSWORD_HASH), _q("9000000000"), _q("admin"))]
    for row in data.users.itertuples():
        users.append((str(row.user_id + 1), _q(row.name), _q(row.email), _q(DEMO_PASSWORD_HASH), _q(row.phone), _q("user")))
    lines += _insert("User", ["Uid", "Uname", "email", "Password", "Phone_no", "Role"], users)

    tx = data.transactions
    expenses = [
        (str(r.user_id + 1), _q(r.category), f"{r.amount:.2f}", _q(r.date.strftime("%Y-%m-%d")), _q(r.description), _q(r.payment_method))
        for r in tx.itertuples()
    ]
    lines += _insert("Expense", ["Uid", "category", "amount", "date", "description", "Payment_Method"], expenses)
    lines += _insert("Income", ["Uid", "Month", "Income"],
                     [(str(r.user_id + 1), _q(r.month), f"{r.income:.2f}") for r in data.incomes.itertuples()])
    lines += _insert("Budget", ["Uid", "Month", "Amount"],
                     [(str(r.user_id + 1), _q(r.month), f"{r.amount:.2f}") for r in data.budgets.itertuples()])
    lines += ["", "COMMIT;", ""]
    return "\n".join(lines)


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--users", type=int, default=8)
    parser.add_argument("--months", type=int, default=24)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--out", default=str(PROJECT_ROOT / "database" / "seed_demo.sql"))
    args = parser.parse_args(argv)
    sql = build_sql(args.users, args.months, args.seed)
    Path(args.out).write_text(sql)
    print(f"wrote {args.out} ({len(sql) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
